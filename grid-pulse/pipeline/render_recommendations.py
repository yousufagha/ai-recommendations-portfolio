"""Render RECOMMENDATIONS.md from validation/golden_values.json, so figures cannot drift from the evidence."""
from __future__ import annotations

import json
from pathlib import Path

LATEST = 2026


def pick(rows, key, fy=LATEST):
    return {r["region_code"][:-1]: r[key] for r in rows if r["fy"] == fy}


def span(rows, region, key):
    v = [r[key] for r in rows if r["region_code"] == region + "1" and 2023 <= r["fy"] <= LATEST]
    return min(v), max(v)


def render(d: dict) -> str:
    conc, cap, shift, batt, reg = (d[k] for k in ["cost_concentration", "cap_value", "load_shift", "battery_upper_bound", "price_regimes"])
    c = pick(conc, "top_1pct_cost_share")
    k = pick(cap, "cap_300_aud_mwh")
    s = pick(shift, "saving_aud_per_mw_year")
    b = pick(batt, "gross_aud_per_mw_year")
    n = pick(reg, "negative_time_share")
    n23 = pick(reg, "negative_time_share", 2023)
    jo = pick(d["negative_share_jul_oct"], "negative_time_share")
    jo_now = pick(d["negative_share_jul_oct"], "negative_time_share", LATEST + 1)
    cap_lo, cap_hi = span(cap, "NSW", "cap_300_aud_mwh")
    sa_lo, sa_hi = span(shift, "SA", "saving_aud_per_mw_year")
    vic_lo, vic_hi = span(shift, "VIC", "saving_aud_per_mw_year")
    bsa_lo, bsa_hi = span(batt, "SA", "gross_aud_per_mw_year")
    return f"""# Draft recommendations

Generated by `pipeline/render_recommendations.py`. Analysis of public AEMO data, not financial or investment advice. FY means July to June. Figures are FY{LATEST} unless a range is shown, and the range covers FY2023 to FY{LATEST}.

## 1. Retailers: hold South Australian cap cover through mild years

**In plain English:** a tiny share of very expensive moments made up {c['SA']:.0%} of South Australia's wholesale power cost, so insurance against them is worth keeping even after a quiet year.

**Finding:** in FY{LATEST}, the dearest 1% of intervals carried {c['SA']:.0%} of SA wholesale cost, against {c['VIC']:.0%} in Victoria and {c['QLD']:.0%} in Queensland. The gross payoff of a $300 cap was ${k['SA']:.1f}/MWh of load in SA, ${k['NSW']:.1f} in NSW and ${k['VIC']:.1f} in Victoria.

**Recommendation:** set cover from several years of tail risk, not last year's outcome, and treat SA separately. In NSW the same payoff ranged from ${cap_lo:.1f} to ${cap_hi:.1f}/MWh, so one mild year says little.

**Limits:** gross of premium, because contract prices are not in this data. Whether cover is good value depends on the premium paid.

## 2. Large energy users: move flexible load out of the evening peak

**In plain English:** power costs far less in the middle of the day than in the early evening, so a business that can run the same equipment a few hours earlier could save real money.

**Finding:** moving 1 MW for 4 hours each weekday from the 16:00 to 21:00 window to the 10:00 to 16:00 window avoided ${s['SA']:,.0f} a year at spot prices in SA, ${s['QLD']:,.0f} in Queensland, ${s['NSW']:,.0f} in NSW and ${s['VIC']:,.0f} in Victoria.

**Recommendation:** prioritise shifting in SA and Queensland, and test the case at FY{LATEST} prices rather than the peak year. The range is ${sa_lo:,.0f} to ${sa_hi:,.0f} in SA and ${vic_lo:,.0f} to ${vic_hi:,.0f} in Victoria.

**Limits:** spot exposure only. Network charges, retail contracts and operating costs are excluded, and a contract customer may capture little of it.

## 3. Storage investors: size cases well below the headline spread

**In plain English:** a battery makes money by buying power when it is cheap and selling when it is dear. These figures are the best case, so a real battery should be expected to earn less from this.

**Finding:** a 1 MW, 2-hour battery cycling once a day had an upper bound of ${b['SA']:,.0f} a year in SA, ${b['NSW']:,.0f} in NSW and ${b['VIC']:,.0f} in Victoria. SA ranged from ${bsa_lo:,.0f} to ${bsa_hi:,.0f}.

**Recommendation:** treat these as ceilings when screening regions. Stress any investment case at the low end of the range, given how far the figures moved in one year.

**Limits:** perfect foresight, 85% round-trip efficiency, no degradation, no price impact, no ancillary services and no ordering constraint. Achievable revenue will differ and may be materially lower on energy alone.

## 4. Policy makers and networks: price daytime surplus into demand

**In plain English:** for {n['VIC']:.0%} of the time in Victoria, the wholesale price of power was below zero, yet many households may never see that. Pricing could encourage people to use power at those times.

**Finding:** prices were negative for {n['VIC']:.0%} of the time in Victoria and {n['SA']:.0%} in SA, up from {n23['VIC']:.0%} and {n23['SA']:.0%} in FY2023. NSW reached {n['NSW']:.0%} and Queensland {n['QLD']:.0%}. The rise is not steady: July to October this year was lower than the same months a year earlier, at {jo_now['VIC']:.1%} against {jo['VIC']:.1%} in Victoria and {jo_now['SA']:.1%} against {jo['SA']:.1%} in SA.

**Recommendation:** tariffs and demand programmes should reward daytime consumption in these regions, because many hours have a market signal that retail customers may not see. Review this if the recent fall continues.

**Limits:** this data shows the price signal and not its causes. Attribution to solar needs the fuel-mix data planned for Phase 3.
"""


if __name__ == "__main__":
    Path("RECOMMENDATIONS.md").write_text(render(json.loads(Path("validation/golden_values.json").read_text())))
    print("wrote RECOMMENDATIONS.md")
